public class Persona {
    //atributos
    public String nombre;
    public String apellido;
    public int edad;
    public char sexo;

    //constructor sin parámetros
    public Persona(){
        this.nombre = "Alam";
        this.apellido = "Brito";
        this.edad = 23;
        this.sexo = 'm';
    }

    public Persona(String nombre,String apellido,int edad,char sexo)
    {
        this.nombre = nombre;
        this.apellido = apellido;
        this.edad = edad;
        this.sexo = sexo;
    }








}
